import { build } from "esbuild";
import { writeFile, readFile } from "node:fs/promises";
const worker = await readFile(
  "node_modules/pdfjs-dist/build/pdf.worker.min.mjs",
  "utf8",
);
const result = await build({
  entryPoints: ["scripts/pdf-viewer.js"],
  bundle: true,
  write: false,
  format: "iife",
  target: "es2022",
});
const statusFont = (
  await readFile("assets/fonts/EBGaramond_400Regular.ttf")
).toString("base64");
const escapeScript = (value) => value.replaceAll("</script", "<\\/script");
const html = `<!doctype html><html><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline' blob:; worker-src blob:; style-src 'unsafe-inline'; font-src data:; img-src data: blob:"><meta name="viewport" content="width=device-width,initial-scale=1"><style>@font-face{font-family:EBGaramond;src:url(data:font/ttf;base64,${statusFont}) format('truetype')}body{margin:0;background:#ecefe9}canvas{width:100%;height:auto}#status{padding:16px;font-family:EBGaramond,serif}</style><div id="status"></div><canvas id="page"></canvas><script>window.pdfWorkerSource=${escapeScript(JSON.stringify(worker))};\n${escapeScript(result.outputFiles[0].text)}</script></html>`;
await writeFile(
  "src/pdfHtml.ts",
  "// Generated by npm run bundle:pdf. PDF.js is bundled locally.\nexport const pdfHtml = " +
    JSON.stringify(html) +
    ";\n",
);
